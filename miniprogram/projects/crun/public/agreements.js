function segments(text) {
	return String(text).split('**').map((t, i) => ({ t, b: i % 2 === 1 })).filter(x => x.t);
}

/** 返回可直接渲染的协议：标题、日期行和段落（段落拆成加粗/普通片段）。未知 key 返回 null。 */
function get(key) {
	if (!Object.prototype.hasOwnProperty.call(AGREEMENTS, key)) return null;
	const a = AGREEMENTS[key];
	return {
		key, title: a.title, version: a.version, meta: a.meta.slice(),
		blocks: a.blocks.map(b => typeof b === 'string' ? { type: 'p', segments: segments(b) } : { type: 'h', text: b.h })
	};
}

module.exports = { get, keys: Object.keys(AGREEMENTS) };
